# A list uses square brackets []
my_list = [7,8,2]

# A tuple uses parentheses ()
my_tuple = (1, 2, 3)

# Lists are mutable (can be changed)
my_list.append(4)

# Tuples are immutable (cannot be changed)
# my_tuple.append(4)  # This will raise an AttributeError

# Print both to see the difference
print(my_list)
print(my_tuple)
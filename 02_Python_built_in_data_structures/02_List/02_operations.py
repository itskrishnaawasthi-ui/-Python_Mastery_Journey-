#OPERATIONS
numbers = [1, 2, 3]


numbers.append(4)
print(numbers)

numbers.insert(1, 10)
print(numbers)
#Remove element by value
numbers.remove(2)
print(numbers)

numbers.remove(3)
print(numbers)

#Remove element by index
numbers.pop(2)
print(numbers)

# Reverse list
numbers.reverse()
print(numbers)

# Sort list
numbers.sort()
print(numbers)
